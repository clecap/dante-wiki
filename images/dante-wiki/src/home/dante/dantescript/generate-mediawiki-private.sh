#!/bin/bash

source /home/dante/dantescript/common-defs.sh     # Read library functions
loadSecrets                                       # Load the secrets file

if [ -f "$MOUNT/$TARGET/mediawiki-PRIVATE.php" ]; then
    printf "\n${ERROR}*** generate-mediawiki-private.sh: mediawiki-PRIVATE.php already existing - will delete and regenerate${RESET}\n"
    rm ${MOUNT}/$TARGET/mediawiki-PRIVATE.php
    touch ${MOUNT}/$TARGET/mediawiki-PRIVATE.php
    chmod 600 ${MOUNT}/$TARGET/mediawiki-PRIVATE.php    
    printf "   DONE deleting\n"
  else
    printf "\n*** generate-mediawiki-private.sh: : mediawiki-PRIVATE.php not found - will generate one\n"
fi


cat <<EOF >> ${MOUNT}/$TARGET/mediawiki-PRIVATE.php
<?php

  // This file is generated by generate-mediawiki-private.sh from values of the local docker secret
  // DO NOT EDIT THIS FILE but adjust values in the configuration file

\$wgPasswordSender = "${SMTP_FROM}";          // address of the sending email account

\$wgSMTP = [
    'host'     => '${SMTP_HOST}',                // hostname of the smtp server of the email account
    'IDHost'   => '${MY_DOMAINNAME}',            // sub(domain) of your wiki
    'port'     => ${SMTP_PORT},                  // SMTP port to be used
    'username' => '${SMTP_USER}',                // username of the email account
    'password' => '${SMTP_PASSWORD}',            // password of the email account
    'auth'     => true                           // shall authentisation be used
];

\$wgLocaltimezone="${MW_TIMEZONE}";

?>
EOF


chown www-data:www-data ${MOUNT}/$TARGET/mediawiki-PRIVATE.php

printf "DONE generating mediawiki-PRIVATE.php\n"

